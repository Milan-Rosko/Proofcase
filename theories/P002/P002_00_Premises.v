Section targets.

  (*
  │
  │          Abstract instance type for unrestricted Hilbert's Tenth
  │          Problem over ℕ, together with its associated yes-predicate.
  │          Leaving these abstract allows the target statement below to
  │          be matched against any specific formalization of H10
  │          without committing to one.
  │
  *)
  
  (*          h10_n_instance : Type, h10_n_yes : h10_n_instance → Prop          *)

  Parameter h10_n_instance : Type.
  Parameter h10_n_yes : h10_n_instance -> Prop.

  (*
  │
  │          Target: unrestricted H10 over ℕ admits no extensional
  │          decider. This is the statement of the
  │          Davis–Putnam–Robinson–Matiyasevich theorem, re-expressed in
  │          the `decides` vocabulary of this file so that reductions
  │          into and out of P002 can be phrased in a uniform idiom.
  │
  *)
  
  (*  h10_n_undecidable ⇔ ∀ f : h10_n_instance → Bool. ¬ decides(h10_n_yes, f)  *)

  Definition h10_n_undecidable : Prop :=
    forall solver : h10_n_instance -> bool,
    ~ decides h10_n_yes solver.

  (*
  │
  │          Abstract instance type for the degree-two (quadratic)
  │          restriction of H10 over ℕ, together with its yes-predicate.
  │          As above, these are kept abstract so that the target
  │          statement is not tied to a specific syntax for quadratic
  │          Diophantine systems.
  │
  *)
  
  Parameter h10_quadratic_n_instance : Type.

  Parameter h10_quadratic_n_yes : h10_quadratic_n_instance -> Prop.

  (*
  │
  │          Ambient comparison target: degree-two H10 over ℕ admits an
  │          extensional decider. This abstract predicate is retained as
  │          background vocabulary only. It must not be read as
  │          asserting that the current P002 project has established a
  │          single-cubic frontier result; the live P002 certification
  │          route is family-level, and the quartic roadmap sits above
  │          it.
  │
  *)
  
  (*     h10_quadratic_n_decidable ⇔ ∃ f : h10_quadratic_n_instance → Bool.     *)
  (*                      decides(h10_quadratic_n_yes, f)                       *)

  Definition h10_quadratic_n_decidable : Prop :=
    exists solver : h10_quadratic_n_instance -> bool,
    decides h10_quadratic_n_yes solver.

End targets.

