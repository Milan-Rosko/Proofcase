(*
│
│          Projection of a code, together with an evaluator, to an
│          ordinary boolean function ℕ → Bool. The projected function
│          returns `true` exactly when the evaluator yields `Some
│          true`, and `false` in every other case — whether `Some
│          false`, `None`, or any intermediate diverging outcome. This
│          projection constitutes the canonical bridge from the coded
│          solver model to the extensional `decides` notion.
│
*)

(*  code_to_solver(eval, e) ≔ λ s. if eval(e, s) = Some true then true else   *)
(*                                   false                                    *)

Definition code_to_solver
  (eval_code : eval_code_sig)
  (e : decider_code) : nat -> bool :=
  fun s =>
  match eval_code e s with
  | Some true => true
  | _ => false
  end.

(*
│
│          Under totality of the coded solver model, any witness of
│          `correct_code_over` for a yes-language P projects, via
│          `code_to_solver`, to a genuine extensional decider for P.
│          This lemma provides the precise sense in which the coded
│          correctness notion introduced here is conservative over the
│          classical extensional decider notion.
│
*)

(*    coded_solver_total(eval, tot) ∧ correct_code_over(P, eval, tot, e) ⇒    *)
(*                    decides(P, code_to_solver(eval, e))                     *)

Lemma correct_code_over_implies_decides :
  forall (P : nat -> Prop) eval_code total_code e,
  coded_solver_total eval_code total_code ->
  correct_code_over P eval_code total_code e ->
  decides P (code_to_solver eval_code e).
Proof.
  intros P eval_code total_code e Htot Hcorr.
  destruct Hcorr as [He_total He_corr].
  unfold decides, code_to_solver.
  intro s.
  split.
  - destruct (eval_code e s) eqn:Hev.
  + destruct b.
  * intros _.
  destruct (He_corr s) as [Hforward _].
  exact (Hforward Hev).
  * discriminate.
  + discriminate.
  - intro HP.
  destruct (Htot e s He_total) as [b Hb].
  rewrite Hb.
  destruct b.
  + reflexivity.
  + exfalso.
  destruct (He_corr s) as [_ Hbackward].
  specialize (Hbackward HP).
  rewrite Hb in Hbackward.
  discriminate.
Qed.

(*
│
│          Specialization of the preceding lemma to the P002 coded
│          yes-language. Downstream refutations show that no code can
│          satisfy the antecedent, and the present lemma is what lifts
│          those refutations from the coded model to an extensional
│          undecidability statement.
│
*)

(* coded_solver_total(eval, tot) ∧ h10_nd3n_correct_code_over(eval, tot, e) ⇒ *)
(*            decides(h10_nd3n_yes_code, code_to_solver(eval, e))             *)

Lemma h10_nd3n_correct_code_implies_decides :
  forall eval_code total_code e,
  coded_solver_total eval_code total_code ->
  h10_nd3n_correct_code_over eval_code total_code e ->
  decides h10_nd3n_yes_code (code_to_solver eval_code e).
Proof.
  intros eval_code total_code e Htot Hcorr.
  eapply correct_code_over_implies_decides.
  - exact Htot.
  - exact Hcorr.
Qed.

