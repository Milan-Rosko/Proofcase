(*
│
│          A computational solver is modelled abstractly as a
│          natural-number code together with an evaluator `eval_code`
│          and a totality predicate `total_code`. Keeping the
│          evaluator and the totality predicate abstract, rather than
│          pinning them to a specific universal machine, ensures that
│          the results of this file apply uniformly to any reasonable
│          model of computation — Turing machines, μ-recursive
│          functions, or Rocq's own extraction target — provided it
│          exposes these two signatures.
│
*)
(*
│
│          This abstraction is exactly what allows the later FM
│          realization to plug in the execution semantics of 𝔐 without
│          changing any of the premise-layer target statements. The
│          machine model should instantiate these symbols, not rewrite
│          them.
│
*)

(*  decider_code ≔ ℕ, eval_code : ℕ → ℕ → Option Bool, total_code : ℕ → Prop  *)
(*Concrete later reading: eval_code(e,s) = Some b may be realized as “𝔐_e(s) ↓*)
(*       b”, while total_code(e) asserts that 𝔐_e halts on every input.       *)

Definition decider_code : Type := nat.
Definition eval_code_sig : Type := decider_code -> nat -> option bool.
Definition total_code_sig : Type := decider_code -> Prop.

(*
│
│          A coded decider e is correct for a yes-language P when two
│          conditions hold: (i) e is accepted by the totality
│          predicate, and (ii) its evaluator returns `Some true` on
│          exactly the yes-instances of P. The behaviour on `Some
│          false` is not postulated separately; in conjunction with
│          the totality condition below — under which every accepted
│          code terminates with some boolean answer on every input —
│          this suffices to recover an ordinary boolean decider on
│          codes, as established by
│          `correct_code_over_implies_decides`.
│
*)

(*  correct_code_over(P, eval, tot, e) ⇔ tot(e) ∧ ∀ s ∈ ℕ. eval(e, s) = Some  *)
(*                                true ↔ P(s)                                 *)

Definition correct_code_over
  (P : nat -> Prop)
  (eval_code : eval_code_sig)
  (total_code : total_code_sig)
  (e : decider_code) : Prop :=
  total_code e /\
  forall s, eval_code e s = Some true <-> P s.

(*
│
│          Totality property of the coded solver model: every code
│          accepted by the totality predicate terminates with some
│          boolean output on every input. This property is precisely
│          what distinguishes a decider code from a merely
│          semi-deciding (partial) code, and it is the crucial
│          ingredient that permits the conversion of a
│          `correct_code_over` witness into an extensional `decides`
│          witness.
│
*)

(*   coded_solver_total(eval, tot) ⇔ ∀ e, s. tot(e) ⇒ ∃ b ∈ {true, false}.    *)
(*                            eval(e, s) = Some b                             *)

Definition coded_solver_total
  (eval_code : eval_code_sig)
  (total_code : total_code_sig) : Prop :=
  forall e input,
  total_code e ->
  exists b, eval_code e input = Some b.

(*
│
│          Specialization of `correct_code_over` to the P002 coded
│          yes-language. This is the predicate whose uninhabitation is
│          established by the coded no-solver endpoint in the
│          downstream development.
│
*)

(*                 h10_nd3n_correct_code_over(eval, tot, e) ⇔                 *)
(*             correct_code_over(h10_nd3n_yes_code, eval, tot, e)             *)

Definition h10_nd3n_correct_code_over
  (eval_code : eval_code_sig)
  (total_code : total_code_sig)
  (e : decider_code) : Prop :=
  correct_code_over h10_nd3n_yes_code eval_code total_code e.

