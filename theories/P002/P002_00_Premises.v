(*
│
│          The project-level no-decider target says that no total
│          boolean solver decides `p002_yes`. In this premise file it
│          is only a target statement; later files determine which
│          hypotheses imply it.
│
*)

(*       P002Undecidable ⇔ ∀ f : P002Instance → Bool. ¬ DecidesP002(f)        *)

Definition p002_semantic_undecidable : Prop :=
  forall solver : p002_instance -> bool,
  ~ decides_p002 solver.

(*
│
│          The concrete family-level no-decider target says that no
│          total boolean solver decides finite cubic-family
│          satisfiability. It talks about finite families over one
│          shared valuation, not about a single cubic equation.
│
*)

(*        FamilyUndecidable ⇔ ∀ f : Family₃ → Bool. ¬ DecidesFamily(f)        *)

Definition cubic_family_semantic_undecidable : Prop :=
  forall solver : cubic_family_instance -> bool,
  ~ decides_cubic_family solver.
