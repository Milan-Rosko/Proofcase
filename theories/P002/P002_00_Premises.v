(*
│
│          Syntactic monomials of total degree at most three. The four
│          constructors denote, respectively, the constant monomial 1,
│          a variable xᵢ, a quadratic product xᵢ·xⱼ, and a cubic
│          product xᵢ·xⱼ·xₖ. This cubic bound is a local normal form
│          coming from the FM carryless/Fibonacci compilation surface;
│          it is not itself the final semantic claim of P002. Variable
│          indices are drawn from ℕ without restriction at this level;
│          their admissibility relative to a specific equation's arity
│          is enforced separately by the well-formedness predicate in
│          the next section.
│
*)

(*            monomial ::= 1 ∣ xᵢ ∣ xᵢ·xⱼ ∣ xᵢ·xⱼ·xₖ (i, j, k ∈ ℕ)            *)

Inductive monomial : Type :=
| m_const
| m_linear (i : nat)
| m_quadratic (i j : nat)
| m_cubic (i j k : nat).

(*
│
│          A term pairs a natural-number coefficient with a monomial.
│          Restricting coefficients to ℕ is a deliberate normal-form
│          choice: any cubic Diophantine equation with integer
│          coefficients can be rewritten, without loss of generality,
│          as an equality of two sums of ℕ-coefficient monomials by
│          moving negative summands to the opposite side.
│
*)

(*                  term ≔ (c, μ) with c ∈ ℕ, μ a monomial;                   *)
(*                               ⟦term⟧ ≡ c · μ                               *)

Record term : Type := {
  coeff : nat;
  mono : monomial
}.

(*
│
│          An equation is a triple consisting of a declared arity and
│          two lists of terms representing the left- and right-hand
│          sides. Writing equations in the form LHS = RHS, rather than
│          P = 0, is what permits both sides to range over ℕ and is
│          the necessary counterpart of the ℕ-coefficient normal form
│          adopted above.
│
*)

(*                   h10_nd3n_equation ≔ ⟨n, Σᵢ lᵢ, Σⱼ rⱼ⟩                    *)
(*      with n ∈ ℕ and each lᵢ, rⱼ a degree-≤3 term over x₀, …, x_{n−1}       *)

Record h10_nd3n_equation : Type := {
  var_count : nat;
  lhs_terms : list term;
  rhs_terms : list term
}.

(*
│
│          A valuation assigns a natural number to every variable
│          index. Representing valuations as total functions ℕ → ℕ,
│          rather than as finite vectors, removes the need to carry an
│          arity proof alongside each valuation; values at indices
│          outside the declared arity of a given equation are
│          inaccessible to that equation by well-formedness and are
│          therefore immaterial.
│
*)

(*                           valuation ≔ ρ : ℕ → ℕ                            *)

Definition valuation : Type := nat -> nat.

(*
