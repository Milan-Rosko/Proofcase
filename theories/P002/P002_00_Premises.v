  OVERVIEW

  This file is the canonical semantic surface of the P002 problem statement.
  Its role is to fix, in an immutable form, (i) the low-degree atomic
  equation language emitted by the carryless Fibonacci/FM compilation layers,
  (ii) the family-level satisfiability language that is the current semantic
  ground truth of P002, (iii) the extensional and coded notions of decider
  against which all downstream claims are stated, and (iv) the target
  predicates that later certification layers may use or compare against,
  including the quartic single-equation route that sits strictly above the
  family layer.

  No later file in the development is permitted to redefine any of the
  notions introduced here; downstream layers may only build on top of them.
  This file is intentionally assumption-free at the problem layer: it may
  declare abstract interfaces such as decoders or evaluators, but any
  non-logical coverage, surjectivity, reduction, or reflection debt must live
  in a rewrite phase or in a later concrete realization layer, not here.

  The file is organized in eight sections: proof environment, low-degree
  atomic syntax, well-formedness, semantics, the extensional solver notion,
  the coded solver notion, the coded-to-extensional communication lemmas, and
  the public target statements. The atomic language happens to be cubic
  because that is the local degree bound generated by the FM carryless
  arithmetic; the semantic message of the file is not “P002 is about cubic
  single equations” but rather “carryless Fibonacci pairing reduces the hard
  part of MRDP to low-degree atomic families, from which the quartic question
  can be approached cleanly”.

*)

