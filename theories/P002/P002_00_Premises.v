(*
│
│          The classical, extensional notion of a decider: a boolean
│          function `solver` decides a yes-language `yes` when its set
│          of true-answers coincides exactly with the yes-language. No
│          computability or effectivity is asserted at this level;
│          effectivity enters only through the coded solver model
│          introduced below.
│
*)

(*                decides(yes, f) ⇔ ∀ x. f(x) = true ↔ yes(x)                 *)

Definition decides {X : Type} (yes : X -> Prop) (solver : X -> bool) : Prop :=
  forall x, solver x = true <-> yes x.

(*
│
│          Legacy specialization of the extensional decider notion to
│          the atomic single-equation language. This is not the
│          canonical project-level decider notion anymore.
│
*)

(*               decides_h10_nd3n(f) ⇔ decides(h10_nd3n_yes, f)               *)

Definition decides_h10_nd3n (solver : h10_nd3n_instance -> bool) : Prop :=
  decides h10_nd3n_yes solver.

Definition decides_cubic_family (solver : cubic_family_instance -> bool) : Prop :=
  decides cubic_family_yes solver.

Definition decides_p002 (solver : p002_instance -> bool) : Prop :=
  decides p002_yes solver.

(*
│
│          Abstract Gödel decoder: a partial function from
│          natural-number codes to semantic instances. Kept abstract
│          so that this file remains independent of any particular
│          encoding scheme. In the current FM architecture, the first
│          concrete seam where D001 enters P002 is
│          `P002_01__Architecture`, and all later compiler-correctness
│          work should route through that exported FM API rather than
│          import D001 directly.
│
*)
(*
│
│          In the intended concrete realization, the later Vector
│          Iterant layer ℑ will supply a machine-facing codec through
│          the FM machine 𝔐. The present premise file deliberately
│          does not commit to that choice: it only reserves the slot
│          in which a concrete decoder may later be proved correct.
│
*)

(*                       decode : ℕ ⇀ h10_nd3n_instance                       *)
(*   At the concrete FM seam, one later aims for a decoder of the form u ↦    *)
(*              ⌜E⌝_{ℑ,𝔐}, but P002_00 keeps this map abstract.               *)

Parameter decode_h10_nd3n_instance : nat -> option h10_nd3n_instance.

(*
│
│          The decoder is left abstract at the premise level. No
│          coverage or surjectivity property is assumed here: the
│          statement that every semantic instance is represented by
│          some code belongs to a rewrite phase or to the later
│          concrete coding realization, not to the immutable problem
│          statement.
│
*)

(*
│
│          The coded yes-language for single equations is retained as
│          legacy infrastructure around the atomic instance type. It
│          is no longer the main endpoint of P002, but it remains
│          available as part of the fixed premise vocabulary.
│
*)

(*      h10_nd3n_yes_code(u) ⇔ ∃ E. decode(u) = Some E ∧ h10_nd3n_yes(E)      *)

Definition h10_nd3n_yes_code (u : nat) : Prop :=
  exists eqn : h10_nd3n_instance,
  decode_h10_nd3n_instance u = Some eqn /\
  h10_nd3n_yes eqn.

(*
│
│          The converse transfer from the semantic yes-language to the
│          coded yes-language is intentionally absent at the premise
│          level. It requires an additional coverage hypothesis for
│          the abstract decoder, and that obligation belongs to a
│          rewrite phase or to a later concrete codec proof, not to
│          `P002_00_Premises`.
│
*)

(*
│
│          Transfer from the coded yes-language back to the semantic
│          yes-language: every yes-code exhibits a concrete
│          yes-instance together with its decoding. Note that the
│          conclusion is definitionally equal to the hypothesis —
│          `h10_nd3n_yes_code u` unfolds to exactly the existential in
│          the conclusion — so the proof closes by `exact`. The lemma
│          carries no logical content beyond its definition; it exists
│          solely to provide a stable named interface that downstream
│          files can import without depending on the raw unfolding of
│          `h10_nd3n_yes_code`.
│
*)

(*                   h10_nd3n_yes_code(u) ⇒ ∃ E. decode(u)                    *)
(*             = Some E ∧ h10_nd3n_yes(E) (definitional identity)             *)

Lemma h10_nd3n_code_yes_implies_instance_yes :
  forall u : nat,
  h10_nd3n_yes_code u ->
  exists eqn : h10_nd3n_instance,
  decode_h10_nd3n_instance u = Some eqn /\
  h10_nd3n_yes eqn.
Proof.
  intros u Hyes_code.
  exact Hyes_code.
Qed.

