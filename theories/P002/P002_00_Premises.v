*)

(*
│
│          The classical, extensional notion of a decider: a boolean
│          function `solver` decides a yes-language `yes` when its set
│          of true-answers coincides exactly with the yes-language. No
│          machine model is fixed here; this file records only the
│          semantic criterion that later undecidability statements
│          negate.
│
*)

(*                decides(yes, f) ⇔ ∀ x. f(x) = true ↔ yes(x)                 *)

Definition decides {X : Type} (yes : X -> Prop) (solver : X -> bool) : Prop :=
  forall x, solver x = true <-> yes x.

(*
│
│          A concrete family solver decides the finite-family language
│          when it decides the predicate `cubic_family_yes`. This is
│          the shape consumed by the downstream compiler theorems.
│
*)

(*                  DecidesFamily(f) ⇔ Decides(FamilyYes, f)                  *)

Definition decides_cubic_family (solver : cubic_family_instance -> bool) : Prop :=
  decides cubic_family_yes solver.

(*
│
│          A project-level solver decides P002 when it decides the
│          public predicate `p002_yes`. This is only an alias layer
│          over the family-level definition above.
│
*)

(*                    DecidesP002(f) ⇔ Decides(P002Yes, f)                    *)

Definition decides_p002 (solver : p002_instance -> bool) : Prop :=
  decides p002_yes solver.

