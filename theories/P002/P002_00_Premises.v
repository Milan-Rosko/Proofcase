│          Principal family-level endpoint of the reset P002 project:
│          satisfiability of finite low-degree families over ℕ admits
│          no extensional decider. Later FM compilation theorems
│          should therefore land in `p002_yes`, equivalently
│          `cubic_family_yes`, not in `h10_nd3n_yes`. This is the
