  OVERVIEW

  This file is the canonical semantic surface of the P002 problem statement.
  Its role is to fix, in an immutable form, (i) the low-degree atomic
  equation language emitted by the Iterant/FM compilation layers, (ii) the
  family-level satisfiability language that is the current semantic ground
  truth of P002, (iii) the extensional notion of decider against which the
  public endpoint is stated, and (iv) the target predicates that the later
  certification layers actually use.

  No later file in the development is permitted to redefine any of the
  notions introduced here; downstream layers may only build on top of them.
  This file is intentionally assumption-free at the problem layer: it fixes
  syntax, semantics, and the public yes-languages, but leaves all reduction
  work to later files.

  The file is organized in six sections: proof environment, low-degree atomic
  syntax, well-formedness, semantics, the extensional solver notion, and the
  public target statements. The atomic language happens to be cubic because
  that is the local degree bound generated by the Iterant/FM arithmetic; the
  semantic message of the file is not “P002 is about one cubic equation” but
  rather “the retained P002 endpoint is satisfiability of finite low-degree
  families over one shared valuation”.

*)

