Definition p002_semantic_undecidable : Prop :=
  forall solver : p002_instance -> bool,
  ~ decides_p002 solver.

Definition p002_family_semantic_undecidable : Prop :=
  p002_semantic_undecidable.

Definition cubic_family_semantic_undecidable : Prop :=
  forall solver : cubic_family_instance -> bool,
