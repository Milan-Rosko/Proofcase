(*
│
│          An equation family is the premise-level cubic family
│          instance, kept under a local semantic name.
│
*)

(*                    EquationFamily ≔ CubicFamilyInstance                    *)

Definition equation_family : Type := cubic_family_instance.

(*
│
│          A family is well-formed when every equation in it is
│          well-formed.
│
*)

(*                        FamilyWF(Γ) ⇔ ∀ E ∈ Γ. WF(E)                        *)

Definition family_wf (Gamma : equation_family) : Prop :=
  Forall equation_wf Gamma.

(*
│
│          A valuation solves all equations in a family when it solves
│          each listed equation.
│
*)

(*                   SolvesAll(Γ,ρ) ⇔ ∀ E ∈ Γ. Solves(E,ρ)                    *)

Definition solves_all (Gamma : equation_family) (rho : valuation) : Prop :=
  Forall (fun eqn => solves eqn rho) Gamma.

(*
│
│          Family satisfiability is the premise-level cubic-family yes
│          predicate under the local semantic name.
│
*)

(*                      FamilySat(Γ) ≔ CubicFamilyYes(Γ)                      *)

Definition family_satisfiable (Gamma : equation_family) : Prop :=
  cubic_family_yes Gamma.

(*
│
│          The local family-satisfiable predicate is exactly
│          existential solvability by one shared valuation.
│
*)

(*                     FamilySat(Γ) ⇔ ∃ ρ. SolvesAll(Γ,ρ)                     *)

Lemma family_satisfiable_iff :
  forall Gamma,
    family_satisfiable Gamma <-> exists rho, solves_all Gamma rho.
Proof.
  intros Gamma.
  unfold family_satisfiable, cubic_family_yes, solves_all.
  reflexivity.
Qed.

(*
│
│          A monomial contributes one cubic occurrence exactly when it
│          is a cubic monomial.
│
*)

(*                         CubicMonoCount(m) ∈ {0,1}                          *)

Definition cubic_monomial_count (m : monomial) : nat :=
  match m with
  | m_cubic _ _ _ => 1
  | _ => 0
  end.

(*
│
│          A term's cubic count is the cubic count of its monomial.
│
*)

(*                 CubicTermCount(t)=CubicMonoCount(mono(t))                  *)

Definition cubic_term_count (t : term) : nat :=
  cubic_monomial_count (mono t).

(*
│
│          A polynomial's cubic count is the sum of the cubic counts
│          of its terms.
│
*)

(*                   CubicPolyCount(ts)=Σ CubicTermCount(t)                   *)

Fixpoint cubic_poly_count (ts : list term) : nat :=
  match ts with
  | [] => 0
  | t :: ts' => cubic_term_count t + cubic_poly_count ts'
  end.

(*
│
│          An equation's cubic count is the sum of its left and right
│          polynomial cubic counts.
│
*)

(*       CubicEqCount(E)=CubicPolyCount(lhs(E))+CubicPolyCount(rhs(E))        *)

Definition cubic_equation_count (eqn : h10_nd3n_equation) : nat :=
  cubic_poly_count (lhs_terms eqn) + cubic_poly_count (rhs_terms eqn).

(*
│
│          A family's cubic count is the sum of the cubic counts of
│          its equations.
│
*)

(*                   CubicFamilyCount(Γ)=Σ CubicEqCount(E)                    *)

Fixpoint cubic_family_count (Gamma : cubic_family_instance) : nat :=
  match Gamma with
  | [] => 0
  | eqn :: Gamma' => cubic_equation_count eqn + cubic_family_count Gamma'
  end.

(*
│
│          A family's variable bound is the maximum equation arity
│          appearing in the family.
│
*)

(*               FamilyVarBound(Γ)=max { varCount(E) | E ∈ Γ }                *)

Fixpoint family_var_bound (Gamma : cubic_family_instance) : nat :=
  match Gamma with
  | [] => 0
  | eqn :: Gamma' => Nat.max (var_count eqn) (family_var_bound Gamma')
  end.

(*
│
│          Cubic polynomial count distributes over list append.
│
*)

(*       CubicPolyCount(ts ++ us)=CubicPolyCount(ts)+CubicPolyCount(us)       *)

Lemma cubic_poly_count_app :
  forall ts us,
    cubic_poly_count (ts ++ us) = cubic_poly_count ts + cubic_poly_count us.
Proof.
  intros ts us.
  induction ts as [|t ts IH]; simpl.
  - reflexivity.
  - rewrite IH.
    lia.
Qed.

(*
│
│          Cubic family count distributes over family append.
│
*)

(*    CubicFamilyCount(Γ₁ ++ Γ₂)=CubicFamilyCount(Γ₁)+CubicFamilyCount(Γ₂)    *)

Lemma cubic_family_count_app :
  forall Gamma1 Gamma2,
    cubic_family_count (Gamma1 ++ Gamma2) =
    cubic_family_count Gamma1 + cubic_family_count Gamma2.
Proof.
  intros Gamma1 Gamma2.
  induction Gamma1 as [|eqn Gamma1 IH]; simpl.
  - reflexivity.
  - rewrite IH.
    lia.
Qed.

(*
│
│          The variable bound of an appended family is the maximum of
│          the two component bounds.
│
*)

(*    FamilyVarBound(Γ₁ ++ Γ₂)=max(FamilyVarBound(Γ₁),FamilyVarBound(Γ₂))     *)

Lemma family_var_bound_app :
  forall Gamma1 Gamma2,
    family_var_bound (Gamma1 ++ Gamma2) =
    Nat.max (family_var_bound Gamma1) (family_var_bound Gamma2).
Proof.
  intros Gamma1 Gamma2.
  induction Gamma1 as [|eqn Gamma1 IH]; simpl.
  - reflexivity.
  - rewrite IH.
    apply Nat.max_assoc.
Qed.

(*
│
│          Every equation arity in a family is bounded by the family
│          variable bound.
│
*)

(*                  E ∈ Γ ⇒ varCount(E) ≤ FamilyVarBound(Γ)                   *)

Lemma family_var_bound_ge_all :
  forall Gamma,
    Forall (fun eqn => var_count eqn <= family_var_bound Gamma) Gamma.
Proof.
  intro Gamma.
  induction Gamma as [|eqn Gamma IH]; simpl.
  - constructor.
  - constructor.
    + apply Nat.le_max_l.
    + apply Forall_forall.
      intros e Hin.
      rewrite Forall_forall in IH.
      pose proof (IH e Hin) as He.
      eapply Nat.le_trans.
      * exact He.
      * apply Nat.le_max_r.
Qed.

(*
│
│          The zero valuation maps every variable index to zero.
│
*)

(*                             ZeroValuation(i)=0                             *)

Definition zero_valuation : valuation := fun _ => 0.

(*
│
│          The empty family is solved by every valuation.
│
*)

(*                              SolvesAll([],ρ)                               *)

Lemma solves_all_nil :
  forall rho,
    solves_all [] rho.
Proof.
  intro rho.
  constructor.
Qed.

(*
│
│          Solving a nonempty family splits into solving its head
│          equation and its tail family.
│
*)

(*              SolvesAll(E::Γ,ρ) ⇔ Solves(E,ρ) ∧ SolvesAll(Γ,ρ)              *)

Lemma solves_all_cons :
  forall eqn Gamma rho,
    solves_all (eqn :: Gamma) rho <->
    solves eqn rho /\ solves_all Gamma rho.
Proof.
  intros eqn Gamma rho.
  split.
  - intro H.
    inversion H; subst.
    tauto.
  - intros [Heq Hrest].
    constructor; assumption.
Qed.

(*
│
│          Solving a singleton family is the same as solving its only
│          equation.
│
*)

(*                       SolvesAll([E],ρ) ⇔ Solves(E,ρ)                       *)

Lemma solves_all_singleton :
  forall eqn rho,
    solves_all [eqn] rho <->
    solves eqn rho.
Proof.
  intros eqn rho.
  rewrite solves_all_cons.
  split.
  - intros [Heq Hnil].
    exact Heq.
  - intro Heq.
    split.
    + exact Heq.
    + constructor.
Qed.

(*
│
│          Solving an appended family splits into solving both
│          component families under the same valuation.
│
*)

(*          SolvesAll(Γ₁++Γ₂,ρ) ⇔ SolvesAll(Γ₁,ρ) ∧ SolvesAll(Γ₂,ρ)           *)

Lemma solves_all_app :
  forall Gamma1 Gamma2 rho,
    solves_all (Gamma1 ++ Gamma2) rho <->
    solves_all Gamma1 rho /\ solves_all Gamma2 rho.
Proof.
  intros Gamma1 Gamma2 rho.
  induction Gamma1 as [|eqn Gamma1 IH]; simpl.
  - split.
    + intro H.
      split.
      * constructor.
      * exact H.
    + intros [_ H].
      exact H.
  - rewrite !solves_all_cons.
    rewrite IH.
    tauto.
Qed.

(*
│
│          The empty family is well-formed.
│
*)

(*                                FamilyWF([])                                *)

Lemma family_wf_nil :
  family_wf [].
Proof.
  constructor.
Qed.

(*
│
│          Well-formedness of a nonempty family splits into
│          well-formedness of its head equation and tail family.
│
*)

(*                    FamilyWF(E::Γ) ⇔ WF(E) ∧ FamilyWF(Γ)                    *)

Lemma family_wf_cons :
  forall eqn Gamma,
    family_wf (eqn :: Gamma) <->
    equation_wf eqn /\ family_wf Gamma.
Proof.
  intros eqn Gamma.
  split.
  - intro H.
    inversion H; subst.
    tauto.
  - intros [Heq Hrest].
    constructor; assumption.
Qed.

(*
│
│          Well-formedness of a singleton family is well-formedness of
│          its only equation.
│
*)

(*                           FamilyWF([E]) ⇔ WF(E)                            *)

Lemma family_wf_singleton :
  forall eqn,
    family_wf [eqn] <-> equation_wf eqn.
Proof.
  intro eqn.
  rewrite family_wf_cons.
  split.
  - intros [Heq _].
    exact Heq.
  - intro Heq.
    split.
    + exact Heq.
    + constructor.
Qed.

(*
│
│          Family well-formedness distributes over append.
│
*)

(*               FamilyWF(Γ₁++Γ₂) ⇔ FamilyWF(Γ₁) ∧ FamilyWF(Γ₂)               *)

Lemma family_wf_app :
  forall Gamma1 Gamma2,
    family_wf (Gamma1 ++ Gamma2) <->
    family_wf Gamma1 /\ family_wf Gamma2.
Proof.
  intros Gamma1 Gamma2.
  induction Gamma1 as [|eqn Gamma1 IH]; simpl.
  - split.
    + intro H.
      split.
      * constructor.
      * exact H.
    + intros [_ H].
      exact H.
  - rewrite !family_wf_cons.
    rewrite IH.
    tauto.
Qed.

(*
│
│          Any valuation that solves all equations in a family also
│          certifies that the family is well-formed, because `solves`
│          includes equation well-formedness.
│
*)

(*                        SolvesAll(Γ,ρ) ⇒ FamilyWF(Γ)                        *)

Lemma solves_all_implies_family_wf :
  forall Gamma rho,
    solves_all Gamma rho ->
    family_wf Gamma.
Proof.
  intros Gamma rho Hsolves.
  induction Hsolves as [|eqn Gamma Hsolve Hrest IH]; constructor.
  - exact (proj1 Hsolve).
  - exact IH.
Qed.

(*
│
│          The empty family is satisfiable, witnessed by the zero
│          valuation.
│
*)

(*                               FamilySat([])                                *)

Lemma family_satisfiable_nil :
  family_satisfiable [].
Proof.
  apply (proj2 (family_satisfiable_iff [])).
  exists zero_valuation.
  apply solves_all_nil.
Qed.

(*
│
│          A singleton family is satisfiable exactly when its only
│          equation is solvable over ℕ.
│
*)

(*                         FamilySat([E]) ⇔ H10Yes(E)                         *)

Lemma family_satisfiable_singleton :
  forall eqn,
    family_satisfiable [eqn] <-> h10_nd3n_yes eqn.
Proof.
  intro eqn.
  unfold h10_nd3n_yes, solvable_over_nat.
  rewrite family_satisfiable_iff.
  split.
  - intros [rho Hsingle].
    exists rho.
    apply solves_all_singleton.
    exact Hsingle.
  - intros [rho Hsolve].
    exists rho.
    apply solves_all_singleton.
    exact Hsolve.
Qed.

(*
│
│          A satisfiable nonempty family yields one shared valuation
│          solving the head equation and the tail.
│
*)

(*            FamilySat(E::Γ) ⇒ ∃ ρ. Solves(E,ρ) ∧ SolvesAll(Γ,ρ)             *)

Lemma family_satisfiable_cons :
  forall eqn Gamma,
    family_satisfiable (eqn :: Gamma) ->
    exists rho,
      solves eqn rho /\ solves_all Gamma rho.
Proof.
  intros eqn Gamma Hsat.
  apply family_satisfiable_iff in Hsat.
  destruct Hsat as [rho Hall].
  exists rho.
  now apply solves_all_cons.
Qed.

(*
│
│          Satisfiability of an appended family means one shared
│          valuation solves both component families.
│
*)

(*         FamilySat(Γ₁++Γ₂) ⇔ ∃ ρ. SolvesAll(Γ₁,ρ) ∧ SolvesAll(Γ₂,ρ)         *)

Lemma family_satisfiable_app :
  forall Gamma1 Gamma2,
    family_satisfiable (Gamma1 ++ Gamma2) <->
    exists rho, solves_all Gamma1 rho /\ solves_all Gamma2 rho.
Proof.
  intros Gamma1 Gamma2.
  rewrite family_satisfiable_iff.
  split.
  - intros [rho Hsolves].
    exists rho.
    apply solves_all_app in Hsolves.
    exact Hsolves.
  - intros [rho [Hleft Hright]].
    exists rho.
    apply solves_all_app.
    split.
    + exact Hleft.
    + exact Hright.
Qed.

(*
│
│          Every satisfiable family is well-formed.
│
*)

(*                         FamilySat(Γ) ⇒ FamilyWF(Γ)                         *)

Lemma family_satisfiable_implies_family_wf :
  forall Gamma,
    family_satisfiable Gamma ->
    family_wf Gamma.
Proof.
  intros Gamma Hsat.
  apply family_satisfiable_iff in Hsat.
  destruct Hsat as [rho Hsolves].
  now apply (solves_all_implies_family_wf Gamma rho).
Qed.
