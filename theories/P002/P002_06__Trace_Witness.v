Lemma code_run_trace_nth :
  forall next fuel start t,
    t <= fuel ->
    nth t (code_run_trace next fuel start) 0 = code_run_last next t start.
Proof.
  intros next fuel.
  induction fuel as [|fuel IH]; intros start t Hle.
  - assert (t = 0) by lia.
    subst t.
    reflexivity.
  - destruct t as [|t'].
    + reflexivity.
    + simpl.
      apply IH.
      lia.
Qed.

