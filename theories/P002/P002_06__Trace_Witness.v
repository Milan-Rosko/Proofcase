Qed.

Lemma CodeTraceWitness_b_correct :
  forall prog input witness,
    CodeTraceWitness_b prog input witness = true <->
    CodeTraceWitness prog input witness.
Proof.
  intros prog input witness.
  unfold CodeTraceWitness_b.
  set (tr := decode_code_trace witness).
  split.
  - intro H.
    apply Bool.andb_true_iff in H.
    destruct H as [Hstart Hrest].
    apply Bool.andb_true_iff in Hrest.
    destruct Hrest as [Hvalid Heq].
    apply CodeTraceStartsWith_b_correct in Hstart.
    apply ValidCodeTrace_b_correct in Hvalid.
    apply Nat.eqb_eq in Heq.
    exists tr.
    repeat split; assumption.
  - intro H.
    destruct H as [tr' [Hstart [Hvalid Heq]]].
    subst witness.
    assert (Hdecode : decode_code_trace (encode_code_trace tr') = tr').
    {
      apply decode_code_trace_encode_code_trace.
    }
    subst tr.
    apply Bool.andb_true_iff.
    split.
    + rewrite Hdecode.
      apply CodeTraceStartsWith_b_correct.
      exact Hstart.
    + apply Bool.andb_true_iff.
      split.
      * rewrite Hdecode.
        apply ValidCodeTrace_b_correct.
        exact Hvalid.
      * apply Nat.eqb_eq.
        rewrite Hdecode.
        reflexivity.
Qed.

Theorem FMValidTrace_b_correct :
  forall prog input witness,
    FMValidTrace_b prog input witness = true <->
    FMValidTrace prog input witness.
Proof.
  intros prog input witness.
  unfold FMValidTrace_b.
  rewrite CodeTraceWitness_b_correct.
  symmetry.
  apply FMValidTrace_iff_CodeTraceWitness.
Qed.

Theorem FMValidTrace_decidable :
  forall prog input witness,
    {FMValidTrace prog input witness} + {~ FMValidTrace prog input witness}.
Proof.
  intros prog input witness.
  destruct (FMValidTrace_b prog input witness) eqn:Hb.
  - left.
    apply FMValidTrace_b_correct.
    exact Hb.
  - right.
    intro Hvalid.
    apply FMValidTrace_b_correct in Hvalid.
    rewrite Hvalid in Hb.
    discriminate.
Qed.

Fixpoint search_FMValidTrace_upto
    (prog : MachineProgram) (input bound : nat) : option nat :=
  match bound with
  | 0 =>
      if FMValidTrace_b prog input 0 then Some 0 else None
  | S bound' =>
      match search_FMValidTrace_upto prog input bound' with
      | Some witness => Some witness
      | None =>
          if FMValidTrace_b prog input (S bound')
          then Some (S bound')
          else None
      end
  end.

(*@inline@[[`search_FMValidTrace_upto` is the bounded constructive search companion to `FMValidTrace_b`. It does not solve the open witness-search compiler problem by itself, but it is the exact primitive-recursive search skeleton a future syntax-first `P002_10` layer would need to mirror.]]@*)

Lemma search_FMValidTrace_upto_sound :
  forall prog input bound witness,
    search_FMValidTrace_upto prog input bound = Some witness ->
    witness <= bound /\
    FMValidTrace prog input witness.
Proof.
  intros prog input bound.
  induction bound as [|bound IH]; intros witness Hsearch; simpl in Hsearch.
  - destruct (FMValidTrace_b prog input 0) eqn:Hb.
    + assert (Hwitness : witness = 0).
      { destruct witness; simpl in Hsearch; [reflexivity|discriminate]. }
      subst witness.
      split.
      * lia.
      * apply FMValidTrace_b_correct.
        exact Hb.
    + discriminate.
  - destruct (search_FMValidTrace_upto prog input bound) as [found|] eqn:Hprev.
    + assert (Hwitness : witness = found).
      { inversion Hsearch. reflexivity. }
      subst witness.
      destruct (IH found eq_refl) as [Hle Hvalid].
      split.
      * lia.
      * exact Hvalid.
    + destruct (FMValidTrace_b prog input (S bound)) eqn:Hb.
      * assert (Hwitness : witness = S bound).
        { destruct witness; simpl in Hsearch; [discriminate|inversion Hsearch; reflexivity]. }
        subst witness.
        split.
        -- lia.
        -- apply FMValidTrace_b_correct.
           exact Hb.
      * discriminate.
Qed.

Lemma search_FMValidTrace_upto_complete :
  forall prog input bound witness,
    witness <= bound ->
    FMValidTrace prog input witness ->
    exists found,
      search_FMValidTrace_upto prog input bound = Some found /\
      FMValidTrace prog input found.
Proof.
  intros prog input bound.
  induction bound as [|bound IH]; intros witness Hle Hvalid.
  - assert (witness = 0) by lia.
    subst witness.
    exists 0.
    split.
    + assert (Hb : FMValidTrace_b prog input 0 = true).
      { apply FMValidTrace_b_correct. exact Hvalid. }
      unfold search_FMValidTrace_upto.
      rewrite Hb.
      reflexivity.
    + exact Hvalid.
  - simpl.
    destruct (Nat.eq_dec witness (S bound)) as [Heq|Hneq].
    + subst witness.
      destruct (search_FMValidTrace_upto prog input bound) as [found|] eqn:Hprev.
      * exists found.
        split.
        -- reflexivity.
        -- destruct (search_FMValidTrace_upto_sound prog input bound found Hprev)
             as [_ Hfound].
           exact Hfound.
      * rewrite (proj2 (FMValidTrace_b_correct prog input (S bound))) by exact Hvalid.
        exists (S bound).
        split.
        -- reflexivity.
        -- exact Hvalid.
    + assert (Hlt : witness <= bound) by lia.
      destruct (IH witness Hlt Hvalid) as [found [Hfound Hvalid_found]].
      rewrite Hfound.
      exists found.
      split.
      * reflexivity.
      * exact Hvalid_found.
Qed.

Theorem exists_FMValidTrace_iff_bounded_search :
  forall prog input,
    (exists witness, FMValidTrace prog input witness) <->
    (exists bound found,
        search_FMValidTrace_upto prog input bound = Some found /\
        FMValidTrace prog input found).
Proof.
  intros prog input.
  split.
  - intros [witness Hvalid].
    pose proof
      (search_FMValidTrace_upto_complete
         prog input witness witness (Nat.le_refl witness) Hvalid)
      as Hcomplete.
    destruct Hcomplete as [found [Hsearch Hfound]].
    exists witness, found.
    split.
    + exact Hsearch.
    + exact Hfound.
  - intros [bound [found [Hsearch Hvalid]]].
    exists found.
    exact Hvalid.
Qed.

Theorem CanonicalTraceWitness_unfold :
  forall prog input witness,
    CanonicalTraceWitness prog input witness <->
    FMValidTrace prog input witness.
Proof.
  reflexivity.
Qed.

(*@inline@[[`FMValidTrace_unfold` freezes the public witness boundary: later compiler theorems should target `FMValidTrace`, while state-trace and explicit code-trace lemmas remain auxiliary internal tools. This keeps the arithmetic surface numeric from the start, so the later family compiler never needs to inspect a Coq list of states.]]@*)
(*@unicodemath@[[FMValidTrace(prog,input,W)\;\Leftrightarrow\;RawTraceWitness(prog,input,W).]]@*)

Lemma RawCodeTraceWitnessFrom_unfold :
  forall prog start witness,
    RawCodeTraceWitnessFrom prog start witness <->
    exists fuel,
      witness = encode_code_trace (code_run_trace (StepCode prog) fuel start) /\
      halted_state (decode_state (code_run_last (StepCode prog) fuel start)).
Proof.
  intros prog start witness.
  unfold RawCodeTraceWitnessFrom, encode_code_trace.
  reflexivity.
Qed.

(*@inline@[[`RawCodeTraceWitnessFrom_unfold` exposes the exact arithmetic payload carried by a raw witness: a fuel bound, the encoded run generated by repeated `StepCode`, and a final halting check on the last code. This is the form the later family compiler actually consumes.]]@*)
(*@unicodemath@[[RawCodeTraceWitnessFrom(prog,start,W)\;\Leftrightarrow\;\exists T.\;W=\encode\_code\_trace(code\_run\_trace(StepCode(prog),T,start))]][[\;\wedge\;halted\_state(decode\_state(code\_run\_last(StepCode(prog),T,start))).]]@*)
