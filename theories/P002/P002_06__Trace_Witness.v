Lemma two_j_minus1_ge_self :
  forall j,
    1 <= j ->
    j <= two_j_minus1 j.
Proof.
  intros j Hj.
  rewrite two_j_minus1_formula.
  lia.
Qed.

Lemma sum_fib_odd_shift_ge :
  forall Bx xs,
    all_ge_2 xs ->
    sum_fib xs <= sum_fib (map (fun j => Bx + two_j_minus1 j) xs).
Proof.
  intros Bx xs Hge.
  induction xs as [|a xs IH]; simpl in *.
  - lia.
  - destruct Hge as [Ha Hxs].
    assert (Hidx : a <= Bx + two_j_minus1 a).
    {
      apply Nat.le_trans with (m := two_j_minus1 a).
      - apply two_j_minus1_ge_self.
        lia.
      - lia.
    }
    assert (Hfib : fib a <= fib (Bx + two_j_minus1 a)).
    {
      apply fib_le_of_le.
      exact Hidx.
    }
    specialize (IH Hxs).
    lia.
Qed.

Lemma odd_band_of_sum_ge_right :
  forall x y,
    y <= sum_fib (odd_band_of x y).
Proof.
  intros x y.
  rewrite <- (Z0_sound y) at 1.
  unfold odd_band_of, odd_band.
  simpl.
  apply sum_fib_odd_shift_ge.
  pose proof (Z0_valid y) as [_ [_ Hge]].
  exact Hge.
Qed.

Lemma encode_ge_right_component :
  forall x y,
    y <= encode x y.
Proof.
  intros x y.
  rewrite encode_as_sum.
  rewrite sum_fib_app.
  pose proof (odd_band_of_sum_ge_right x y) as Hodd.
  lia.
Qed.

Lemma encode_nat_list_ge_length :
  forall xs,
    length xs <= encode_nat_list xs.
Proof.
  induction xs as [|x xs IH]; simpl.
  - lia.
  - assert (Hmid : length xs <= encode x (encode_nat_list xs)).
    {
      eapply Nat.le_trans.
      - exact IH.
      - apply encode_ge_right_component.
    }
    lia.
Qed.

(*@inline@[[`encode_nat_list_ge_length` is the key numeric size bound for the fixed-witness compiler route: a coded trace is always at least as large as its list length. This is what later allows a witness-bounded primitive-recursive decoder on the raw number `W` itself.]]@*)

Theorem decode_code_trace_encode_code_trace :
  forall tr,
    decode_code_trace (encode_code_trace tr) = tr.
Proof.
  intros tr.
  unfold decode_code_trace.
  apply decode_code_trace_bounded_encode_code_trace.
  apply encode_nat_list_ge_length.
Qed.

(*@inline@[[`decode_code_trace` is the primitive-recursive fixed-witness decoder: it recovers a whole code trace from its single witness number using only a numeric budget. `decode_code_trace_encode_code_trace` is the exact adequacy theorem that later lets the compiler inspect `W` structurally without any semantic search.]]@*)

Lemma code_run_trace_valid :
  forall prog fuel start,
    halted_state (decode_state (code_run_last (StepCode prog) fuel start)) ->
    ValidCodeTrace prog (code_run_trace (StepCode prog) fuel start).
Proof.
  intros prog fuel.
  induction fuel as [|fuel IH]; intros start Hhalt; simpl in *.
  - exact Hhalt.
  - destruct (code_run_trace (StepCode prog) fuel (StepCode prog start))
      as [|s2 rest] eqn:Htrace.
    + exfalso.
      apply (code_run_trace_nonempty (StepCode prog) fuel (StepCode prog start)).
      exact Htrace.
    + split.
      * pose proof (code_run_trace_head (StepCode prog) fuel (StepCode prog start))
          as Hhead.
        rewrite Htrace in Hhead.
        simpl in Hhead.
        exact Hhead.
      * rewrite <- Htrace.
        apply IH.
        exact Hhalt.
Qed.

Lemma RawTraceWitness_implies_CodeTraceWitness :
  forall prog input witness,
    RawTraceWitness prog input witness ->
    CodeTraceWitness prog input witness.
Proof.
  intros prog input witness Hraw.
  unfold RawTraceWitness, RawCodeTraceWitnessFrom in Hraw.
  destruct Hraw as [fuel [Hwitness Hhalt]].
  exists (code_run_trace (StepCode prog) fuel (start_code input)).
  split.
  - unfold CodeTraceStartsWith.
    destruct (code_run_trace (StepCode prog) fuel (start_code input))
      as [|s0 rest] eqn:Htrace.
    + exfalso.
      apply (code_run_trace_nonempty (StepCode prog) fuel (start_code input)).
      exact Htrace.
    + pose proof (code_run_trace_head (StepCode prog) fuel (start_code input))
        as Hhead.
      rewrite Htrace in Hhead.
      simpl in Hhead.
      exact Hhead.
  - split.
    + apply code_run_trace_valid.
      exact Hhalt.
    + exact Hwitness.
Qed.

Lemma CodeTraceWitness_implies_RawTraceWitnessFrom :
  forall prog start tr witness,
    CodeTraceStartsFrom start tr ->
    ValidCodeTrace prog tr ->
    witness = encode_code_trace tr ->
    RawCodeTraceWitnessFrom prog start witness.
Proof.
  intros prog start tr witness Hstart Hvalid Hwitness.
  revert start witness Hstart Hvalid Hwitness.
  induction tr as [|s1 tr IH]; intros start witness Hstart Hvalid Hwitness.
  - contradiction.
  - destruct tr as [|s2 rest].
    + simpl in Hstart, Hvalid.
      subst s1.
      unfold RawCodeTraceWitnessFrom.
      exists 0.
      simpl.
      split.
      * exact Hwitness.
      * exact Hvalid.
    + simpl in Hstart, Hvalid.
      destruct Hvalid as [Hstep Htail].
      subst s1.
      assert (Htail_start : CodeTraceStartsFrom s2 (s2 :: rest)).
      { reflexivity. }
      specialize (IH s2 _ Htail_start Htail eq_refl).
      unfold RawCodeTraceWitnessFrom in *.
      destruct IH as [fuel [Htail_witness Hhalt]].
      exists (S fuel).
      simpl.
      split.
      * rewrite Hwitness.
        simpl.
        change
          (S
             (encode start (encode_code_trace (s2 :: rest))) =
           S
             (encode start
                (encode_nat_list
                   (code_run_trace (StepCode prog) fuel (StepCode prog start))))).
        rewrite Htail_witness.
        rewrite <- Hstep.
        reflexivity.
      * rewrite <- Hstep.
        exact Hhalt.
Qed.

Lemma CodeTraceWitness_implies_RawTraceWitness :
  forall prog input witness,
    CodeTraceWitness prog input witness ->
    RawTraceWitness prog input witness.
Proof.
  intros prog input witness [tr [Hstart [Hvalid Hwitness]]].
  unfold RawTraceWitness.
  eapply CodeTraceWitness_implies_RawTraceWitnessFrom.
  - exact Hstart.
  - exact Hvalid.
  - exact Hwitness.
Qed.

Theorem RawTraceWitness_iff_CodeTraceWitness :
  forall prog input witness,
    RawTraceWitness prog input witness <->
    CodeTraceWitness prog input witness.
Proof.
  intros prog input witness.
  split.
  - apply RawTraceWitness_implies_CodeTraceWitness.
  - apply CodeTraceWitness_implies_RawTraceWitness.
Qed.

