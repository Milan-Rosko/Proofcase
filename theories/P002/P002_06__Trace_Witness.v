Lemma ValidCodeTrace_b_correct :
  forall prog tr,
    ValidCodeTrace_b prog tr = true <->
    ValidCodeTrace prog tr.
Proof.
  intros prog tr.
  induction tr as [|s1 tr IH]; simpl.
  - split; intro H.
    + discriminate.
    + contradiction.
  - destruct tr as [|s2 rest]; simpl.
    + rewrite halted_code_b_correct.
      apply (ValidCodeTrace_singleton prog s1).
    + rewrite Bool.andb_true_iff.
      rewrite step_matches_b_correct.
      rewrite IH.
      apply (ValidCodeTrace_cons prog s1 s2 rest).
Qed.

