(*@doc.pl@[[We package finite FM executions as single natural-number witnesses in the P002 namespace.]]@*)

(*@doc.pl@[[Only one witness notion is central for the family-level compiler theorem `compile_fm_family_correct`: the numeric predicate `FMValidTrace`.]]@*)

(*@doc.pl@[[The public witness notion is the raw arithmetic witness over encoded traces generated by the fixed projected step `StepCode`. Meta-level state traces are kept only as helper interfaces, not as the compiler-facing boundary.]]@*)

(*@doc.pl@[[The asymptotic “large enough limits” semantics are intentionally deferred to the theorem-only bridge in `P002_98`. They must not enter the compiler half while equations are being constructed.]]@*)

(*@head.end@*)

From P002 Require Export P002_05__Transition_Relation.
From Stdlib Require Import Bool.

Definition StateTrace : Type := list MachineState.
Definition CodeTrace : Type := list EncodedState.

Definition encode_code_trace : CodeTrace -> nat := encode_nat_list.
Definition code_trace_head : nat -> nat := coded_list_head.
Definition code_trace_tail : nat -> nat := coded_list_tail.
Definition code_trace_nth : nat -> nat -> nat := coded_nth.

Fixpoint decode_code_trace_bounded (budget witness : nat) : CodeTrace :=
  match budget with
  | 0 => []
  | S budget' =>
      match witness with
      | 0 => []
      | S _ =>
          code_trace_head witness ::
          decode_code_trace_bounded budget' (code_trace_tail witness)
      end
  end.

Definition decode_code_trace (witness : nat) : CodeTrace :=
  decode_code_trace_bounded witness witness.

Definition trace_state_codes : StateTrace -> CodeTrace := trace_code_list.
Definition encode_state_trace : StateTrace -> nat := encode_trace.

Definition start_code (input : nat) : EncodedState :=
  encode_state (initial_state input).

Definition ValidStateTrace : MachineProgram -> StateTrace -> Prop := ValidTrace.
Definition StateTraceStartsWith (input : nat) : StateTrace -> Prop :=
  trace_starts_with input.
Definition StateTraceWitness : MachineProgram -> nat -> nat -> Prop := TraceWitness.

Definition CodeTraceStartsFrom (start : EncodedState) (tr : CodeTrace) : Prop :=
  match tr with
  | [] => False
  | s0 :: _ => s0 = start
  end.

Definition CodeTraceStartsFrom_b (start : EncodedState) (tr : CodeTrace) : bool :=
  match tr with
  | [] => false
  | s0 :: _ => Nat.eqb s0 start
  end.

Fixpoint ValidCodeTrace (prog : MachineProgram) (tr : CodeTrace) : Prop :=
  match tr with
  | [] => False
  | s1 :: rest =>
      match rest with
      | [] => halted_state (decode_state s1)
      | s2 :: _ =>
          s2 = StepCode prog s1 /\
          ValidCodeTrace prog rest
      end
  end.

Fixpoint ValidCodeTrace_b (prog : MachineProgram) (tr : CodeTrace) : bool :=
  match tr with
  | [] => false
  | s1 :: rest =>
      match rest with
      | [] => halted_code_b s1
      | s2 :: _ =>
          step_matches_b prog s1 s2 && ValidCodeTrace_b prog rest
      end
  end.

Definition CodeTraceStartsWith (input : nat) (tr : CodeTrace) : Prop :=
  CodeTraceStartsFrom (start_code input) tr.

Definition CodeTraceStartsWith_b (input : nat) (tr : CodeTrace) : bool :=
  CodeTraceStartsFrom_b (start_code input) tr.

Definition CodeTraceWitness
    (prog : MachineProgram) (input witness : nat) : Prop :=
  exists tr,
    CodeTraceStartsWith input tr /\
    ValidCodeTrace prog tr /\
    witness = encode_code_trace tr.

Definition RawCodeTraceWitnessFrom
    (prog : MachineProgram) (start witness : nat) : Prop :=
  raw_trace_witness_from
    (StepCode prog)
    (fun s => halted_state (decode_state s))
    start
    witness.

Definition RawTraceWitness
    (prog : MachineProgram) (input witness : nat) : Prop :=
  RawCodeTraceWitnessFrom prog (start_code input) witness.

Definition FMValidTrace : MachineProgram -> nat -> nat -> Prop :=
  RawTraceWitness.

Definition CodeTraceWitness_b
    (prog : MachineProgram) (input witness : nat) : bool :=
  let tr := decode_code_trace witness in
  CodeTraceStartsWith_b input tr &&
  (ValidCodeTrace_b prog tr &&
   Nat.eqb witness (encode_code_trace tr)).

Definition FMValidTrace_b : MachineProgram -> nat -> nat -> bool :=
  CodeTraceWitness_b.

(*@inline@[[`FMValidTrace_b` is the executable fixed-witness checker for the public numeric trace predicate. It matters because the family-level compiler theorem only ever quantifies over raw witness numbers, so any later attempt to replace semantic witness choice with a syntax-first search construction will have to target this checker rather than the meta-level `Prop` interface.]]@*)

Definition CanonicalTraceWitness : MachineProgram -> nat -> nat -> Prop :=
  FMValidTrace.

(*@inline@[[`FMValidTrace` is the unique public witness notion for the P002 compiler route. It is a raw natural-number predicate over encoded traces generated by repeated `StepCode`, which is exactly the shape the compiler is allowed to arithmetize. The family/limit semantics live later, outside the compiler membrane.]]@*)
(*@unicodemath@[[FMValidTrace(prog,input,W)\; \equiv\; RawTraceWitness(prog,input,W).]]@*)

Theorem encode_code_trace_cons_head :
  forall x xs,
    code_trace_head (encode_code_trace (x :: xs)) = x.
Proof.
  exact encode_nat_list_cons_head.
Qed.

Theorem encode_code_trace_cons_tail :
  forall x xs,
    code_trace_tail (encode_code_trace (x :: xs)) = encode_code_trace xs.
Proof.
  exact encode_nat_list_cons_tail.
Qed.

Lemma code_trace_nth_zero :
  forall i,
    code_trace_nth i 0 = 0.
Proof.
  induction i as [|i IHi]; simpl.
  - reflexivity.
  - exact IHi.
Qed.

Theorem code_trace_nth_encode_code_trace :
  forall tr i,
    code_trace_nth i (encode_code_trace tr) = nth i tr 0.
Proof.
  intros tr i.
  revert tr.
  induction i as [|i IHi]; intros [|x xs]; simpl.
  - reflexivity.
  - apply encode_code_trace_cons_head.
  - apply code_trace_nth_zero.
  - change
      (code_trace_nth i (code_trace_tail (encode_code_trace (x :: xs))) =
       nth i xs 0).
    rewrite encode_code_trace_cons_tail.
    exact (IHi xs).
Qed.

(*@inline@[[`code_trace_nth_encode_code_trace` turns numeric trace access back into ordinary list indexing. This is central to `compile_fm_family_correct`, because the trace-family soundness proof must recover per-time codes from the single witness number without leaving the raw numeric interface.]]@*)

Lemma decode_code_trace_bounded_encode_code_trace :
  forall tr budget,
    length tr <= budget ->
    decode_code_trace_bounded budget (encode_code_trace tr) = tr.
Proof.
  intros tr budget.
  revert tr.
  induction budget as [|budget IH]; intros [|x xs] Hlen; simpl in *.
  - reflexivity.
  - lia.
  - reflexivity.
  - change
      (code_trace_head (encode_code_trace (x :: xs)) ::
       decode_code_trace_bounded budget
         (code_trace_tail (encode_code_trace (x :: xs))) =
       x :: xs).
    rewrite encode_code_trace_cons_head.
    rewrite encode_code_trace_cons_tail.
    rewrite (IH xs) by lia.
    reflexivity.
Qed.

Lemma decode_code_trace_bounded_length_le :
  forall budget witness,
    length (decode_code_trace_bounded budget witness) <= budget.
Proof.
  induction budget as [|budget IH]; intros witness; simpl.
  - lia.
  - destruct witness.
    + simpl. lia.
    + simpl.
      specialize (IH (code_trace_tail (S witness))).
      apply le_n_S.
      exact IH.
Qed.

Lemma decode_code_trace_length_le :
  forall witness,
    length (decode_code_trace witness) <= witness.
Proof.
  intro witness.
  unfold decode_code_trace.
  apply decode_code_trace_bounded_length_le.
Qed.

Lemma decode_code_trace_positive :
  forall witness,
    witness <> 0 ->
    0 < length (decode_code_trace witness).
Proof.
  intros [|witness] Hnz; [contradiction|].
  unfold decode_code_trace.
  simpl.
  lia.
Qed.

Lemma nth_decode_code_trace_bounded :
  forall budget witness i,
    i < budget ->
    nth i (decode_code_trace_bounded budget witness) 0 = code_trace_nth i witness.
Proof.
  induction budget as [|budget IH]; intros witness i Hi; [lia|].
  destruct witness as [|witness].
  - destruct i as [|i]; simpl.
    + reflexivity.
    + symmetry.
      apply code_trace_nth_zero.
  - destruct i as [|i]; simpl.
    + reflexivity.
    + apply IH.
      lia.
Qed.

Lemma nth_decode_code_trace :
  forall witness i,
    i < length (decode_code_trace witness) ->
    nth i (decode_code_trace witness) 0 = code_trace_nth i witness.
Proof.
  intros witness i Hi.
  unfold decode_code_trace.
  apply nth_decode_code_trace_bounded.
  eapply Nat.lt_le_trans.
  - exact Hi.
  - apply decode_code_trace_bounded_length_le.
Qed.

