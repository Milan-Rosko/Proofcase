(*                   R; Γ ⊢ᵢ A ∧ R; Γ ⊢ᵢ A → B ⇒ R; Γ ⊢ᵢ B                    *)

Lemma regulator_theory_inductive_derivable_mp_lemma :
  forall R Gamma A B,
    regulator_theory_inductive_derivable R Gamma A ->
    regulator_theory_inductive_derivable R Gamma (Imp A B) ->
    regulator_theory_inductive_derivable R Gamma B.
Proof.
  intros R Gamma A B Harg Himp.
  apply regulator_theory_inductive_mp with (A := A).
  - exact Harg.
  - exact Himp.
Qed.

(*        A ∈ finite_axiom_set_formulas(FT) ⇒ profile, FT; Γ ⊢check A         *)

Lemma finite_axiom_set_checked_derivable_axiom_lemma :
  forall profile T Gamma A,
    In A (finite_axiom_set_formulas T) ->
    finite_axiom_set_checked_derivable profile T Gamma A.
Proof.
  intros profile T Gamma A Hin.
  apply finite_axiom_set_checked_derivable_as_regulator_theory_lemma.
  apply regulator_theory_axiom_checked_derivable_lemma.
  unfold available_axiom_bool,
    finite_axiom_set_to_regulator_theory,
    regulator_theory_with_axiom_set,
    finite_axiom_set_to_axiom_set.
  simpl.
  pose proof
    (finite_axiom_set_contains_bool_complete_lemma T A Hin)
    as Hcontains.
  rewrite Hcontains.
  destruct (logical_axiom_bool profile A);
    reflexivity.
Qed.

