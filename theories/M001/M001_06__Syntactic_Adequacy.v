(*                         R; Γ ⊬check A ⇔ R; Γ ⊬ᵢ A                          *)

Lemma regulator_theory_not_checked_derivable_iff_not_inductive_derivable_lemma :
  forall R Gamma A,
    regulator_theory_not_checked_derivable R Gamma A <->
    regulator_theory_not_inductive_derivable R Gamma A.
Proof.
  intros R Gamma A.
  split.
  - intros Hnot HderI.
    apply Hnot.
    apply regulator_theory_inductive_derivable_implies_checked_lemma.
    exact HderI.
  - intros Hnot Hder.
    apply Hnot.
    apply regulator_theory_checked_derivable_implies_inductive_lemma.
    exact Hder.
Qed.

(*
┌──────────────────────────────────────────────────────────────────────────────┐
│                                                                              │
│                             INDUCTION PRINCIPLE                              │
│                                                                              │
└──────────────────────────────────────────────────────────────────────────────┘
*)

  Checked derivability inherits the induction principle of the inductive
  closure. A caller supplies handlers for assumptions, available axioms, and
  MP; the proof first transports the checked witness through syntactic
  adequacy and then performs ordinary induction on the inductive derivation.

(*  ((∀A. A∈Γ ⇒ P(A)) ∧ (∀A. available_axiom_bool(R,A)=true ⇒ P(A)) ∧ (∀A B.  *)
(*                P(A)∧P(A→B)⇒P(B))) ⇒ (R; Γ ⊢check C ⇒ P(C))                 *)

Theorem regulator_theory_checked_derivable_induction :
  forall R Gamma (P : Formula -> Prop),
    (forall A, In A Gamma -> P A) ->
    (forall A, available_axiom_bool R A = true -> P A) ->
    (forall A B, P A -> P (Imp A B) -> P B) ->
    forall C,
      regulator_theory_checked_derivable R Gamma C ->
      P C.
Proof.
  intros R Gamma P Hassumption Haxiom Hmp C Hder.
  pose proof
    (regulator_theory_checked_derivable_implies_inductive_lemma
      R Gamma C Hder) as HderI.
  clear Hder.
  induction HderI as
    [A Hin
    |A HaxiomA
    |A B Harg IHarg Himp IHimp].
  - apply Hassumption.
    exact Hin.
  - apply Haxiom.
    exact HaxiomA.
  - apply Hmp with (A := A).
    + exact IHarg.
    + exact IHimp.
Qed.
