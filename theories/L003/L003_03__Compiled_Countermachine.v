(*@doc.header@[[Overview]]@*)

(*@doc.pl@[[Concrete compiled-semantics layer for L003. We partition natural-number codes into even base-machine labels and odd diagonal-product labels, define the least output relation generated by those two cases, and verify the abstract `CompilerCorrect` law for this semantics.]]@*)

(*@doc.pl@[[This is a constructive counter-machine semantics for the compiler law. The uniform compiler is the primitive-recursive map `h ↦ 2h+1`; its compiled machine runs the source evaluator on the doubled query and halts precisely on verdict `0`. A standard enumerated machine realizes the same construction by inserting `h` into this fixed program template.]]@*)

