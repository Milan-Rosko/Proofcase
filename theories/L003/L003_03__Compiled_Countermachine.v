  OVERVIEW

  Concrete compiled-semantics layer for L003. We partition natural-number
  codes into even base-machine labels and odd diagonal-product labels, define
  the least output relation generated by those two cases, and verify the
  abstract `CompilerCorrect` law for this semantics.

  “Countermachine” here names this internal relational construction. The file
  does not define a conventional instruction language, step relation,
  universal machine, or compiler into an independently specified operational
  model.

*)

